"""Make a redacted copy of the raw results for submission.

Usage (from the repo root, cmd):
    .venv\\Scripts\\python.exe scripts\\make_submission_copy.py

Reads every results/raw/*.jsonl (read-only; results/raw/ is never modified) and
writes results/submission/<same name>.jsonl with every Groq organization ID
(pattern org_ followed by letters/digits) replaced by "org_REDACTED".
Nothing else is changed: line order, all other fields and byte content stay as
in the raw file. results/submission/REDACTION.md lists every replacement:
file, line number, record id and the JSON field path that contained it.

Re-running regenerates results/submission/ from results/raw/ (the copies are
derived files; the raw files remain the source of truth).
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results" / "raw"
OUT = ROOT / "results" / "submission"
ORG_RE = re.compile(r"org_(?!REDACTED\b)[A-Za-z0-9]+")
REPLACEMENT = "org_REDACTED"


def paths_containing(obj, path="$"):
    """Yield JSON paths of string values that contain an org ID."""
    if isinstance(obj, dict):
        for k, v in obj.items():
            yield from paths_containing(v, f"{path}.{k}")
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            yield from paths_containing(v, f"{path}[{i}]")
    elif isinstance(obj, str) and ORG_RE.search(obj):
        yield path, len(ORG_RE.findall(obj))


def sha256(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def main() -> int:
    files = sorted(RAW.glob("*.jsonl"))
    if not files:
        print("No results/raw/*.jsonl files.")
        return 1
    OUT.mkdir(parents=True, exist_ok=True)
    report = []
    distinct: set[str] = set()
    total = 0
    for src in files:
        raw_hash_before = sha256(src)
        dst = OUT / src.name
        out_lines = []
        hits = []
        with src.open(encoding="utf-8") as f:
            for n, line in enumerate(f, start=1):
                found = ORG_RE.findall(line)
                if found:
                    distinct.update(found)
                    rec = json.loads(line)
                    rid = rec.get("request_id") or rec.get("type")
                    for path, count in paths_containing(rec):
                        hits.append((n, rid, path, count))
                    total += len(found)
                    line = ORG_RE.sub(REPLACEMENT, line)
                out_lines.append(line)
        dst.write_text("".join(out_lines), encoding="utf-8", newline="")
        if sha256(src) != raw_hash_before:  # paranoia: the source must be untouched
            raise SystemExit(f"{src} changed during processing - aborting")
        if ORG_RE.search(dst.read_text(encoding="utf-8")):
            raise SystemExit(f"{dst} still contains an organization ID - aborting")
        report.append((src, dst, raw_hash_before, sha256(dst), hits))
        print(f"{src.name}: {sum(h[3] for h in hits)} replacement(s) in {len({h[0] for h in hits})} record(s)")

    lines = [
        "# Redaction report",
        "",
        f"Generated by `scripts/make_submission_copy.py` at "
        f"{datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')}. Do not edit by hand.",
        "",
        f"Rule: every Groq organization ID (regex `{ORG_RE.pattern}`) was replaced by `{REPLACEMENT}`. "
        "Nothing else was changed. The files in `results/raw/` are the untouched originals.",
        "",
        f"Distinct organization IDs replaced: {len(distinct)}. Total replacements: {total}.",
        "",
    ]
    for src, dst, h_src, h_dst, hits in report:
        lines += [
            f"## {src.name}",
            "",
            f"- raw SHA-256: `{h_src}`",
            f"- submission SHA-256: `{h_dst}`",
            f"- replacements: {sum(h[3] for h in hits)}",
            "",
        ]
        if hits:
            lines += ["| Line | Record | Field | Replacements |", "|---|---|---|---|"]
            lines += [f"| {n} | {rid} | `{path}` | {c} |" for n, rid, path, c in hits]
            lines.append("")
    (OUT / "REDACTION.md").write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {len(report)} file(s) and REDACTION.md to {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
