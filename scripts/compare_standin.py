"""Validate the stand-in against the real service on the same workload (no model calls).

    .venv\\Scripts\\python.exe scripts\\compare_standin.py

Pairs every real eval run (results/raw/run_eval_<setting>_<UTC>.csv + traces) with the stand-in run of the
same setting (run_eval_standin_<setting>_<UTC>.csv, made by `run_eval.py --setting X --standin`), using the
latest run of each kind not listed in results/excluded_runs.csv, and compares, per model call:
    model first token (ms)   time from sending the request to the first visible token
    work (ms)                the final attempt, request sent -> last byte
and end to end: first_token_ms of the results rows.
For each: n, median, p90 for real and stand-in, the ratio of medians, and the two-sample
Kolmogorov-Smirnov distance D (0 = same distribution, 1 = disjoint). Writes docs/standin_validation.md.
"""

from __future__ import annotations

import csv
import json
import math
import re
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "results" / "raw"


def pct(v, p):
    s = sorted(v)
    return s[max(0, math.ceil(p / 100 * len(s)) - 1)] if s else None


def ks(a, b) -> float:
    if not a or not b:
        return float("nan")
    xs = sorted(set(a) | set(b))
    sa, sb = sorted(a), sorted(b)
    import bisect
    return max(abs(bisect.bisect_right(sa, x) / len(sa) - bisect.bisect_right(sb, x) / len(sb)) for x in xs)


def excluded() -> set:
    p = ROOT / "results" / "excluded_runs.csv"
    return {e["run_stamp"] for e in csv.DictReader(p.open(encoding="utf-8"))} if p.exists() else set()


def latest(kind: str, setting: str):
    ex = excluded()
    files = [f for f in sorted(RAW.glob(f"run_{kind}_{setting}_*.csv"))
             if re.search(r"\d{8}T\d{6}Z", f.name).group(0) not in ex]
    return files[-1] if files else None


def measures(run_csv: Path) -> dict:
    tr = run_csv.with_name(run_csv.name.replace("run_", "traces_", 1)).with_suffix(".jsonl")
    m = {"route model first token": [], "route work": [], "draft model first token": [], "draft work": [],
         "end-to-end first token": []}
    for line in tr.read_text(encoding="utf-8").splitlines():
        r = json.loads(line)
        if r.get("type") != "step" or r.get("step") not in ("route", "draft") or r.get("outcome") != "ok":
            continue
        if r.get("model_first_token_ms") is not None:
            # first token inside the final (accepted) attempt: without rate-gate waits and 429 retries
            m[f"{r['step']} model first token"].append(r["model_first_token_ms"] - (r.get("wait_ms") or 0)
                                                       - (r.get("retry_ms") or 0))
        m[f"{r['step']} work"].append(r["work_ms"])
    for row in csv.DictReader(run_csv.open(encoding="utf-8")):
        if row["status"] == "ok" and row["first_token_ms"]:
            m["end-to-end first token"].append(float(row["first_token_ms"]))
    return m


def main() -> int:
    out = ["# Stand-in validation", "", "Same questions and retrieval setting, sequential, real Groq vs stand-in. "
           "Generated by scripts/compare_standin.py. Times in ms. Model-call measures use the final, accepted attempt "
           "(rate-gate waits and 429 retries removed); end-to-end first token includes them. "
           "D = Kolmogorov-Smirnov distance. Calibration sources: see sources in standin/calibration.json.", ""]
    found = False
    for setting in ("small", "medium", "large"):
        real, stand = latest("eval", setting), latest("eval_standin", setting)
        if not real or not stand:
            out.append(f"- {setting}: not measured (real run: {real.name if real else 'none'}, stand-in run: "
                       f"{stand.name if stand else 'none'})")
            continue
        found = True
        a, b = measures(real), measures(stand)
        out += [f"## {setting}: {real.name} vs {stand.name}", "",
                "| Measure | n real / stand-in | median real | median stand-in | ratio | p90 real | p90 stand-in | D |",
                "|---|---|---|---|---|---|---|---|"]
        for k in a:
            x, y = a[k], b[k]
            if not x or not y:
                out.append(f"| {k} | {len(x)} / {len(y)} | not measured | | | | | |")
                continue
            mx, my = statistics.median(x), statistics.median(y)
            out.append(f"| {k} | {len(x)} / {len(y)} | {mx:,.0f} | {my:,.0f} | {my / mx:.2f} | {pct(x, 90):,.0f} | "
                       f"{pct(y, 90):,.0f} | {ks(x, y):.2f} |")
        out.append("")
    (ROOT / "docs" / "standin_validation.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))
    return 0 if found else 1


if __name__ == "__main__":
    sys.exit(main())
